// ── Behavioural tests ─────────────────────────────────────────────────

describe('sql.generator — behaviour', () => {
  it('dependency ordering: referenced tables appear before referencing tables', () => {
    const sql = generateSql(validLibrary, 'postgresql');
    const createTableOrder = [...sql.matchAll(/CREATE TABLE "(\w+)"/g)].map((m) => m[1]);

    const authorsIdx = createTableOrder.indexOf('authors');
    const booksIdx = createTableOrder.indexOf('books');
    const membersIdx = createTableOrder.indexOf('members');
    const borrowsIdx = createTableOrder.indexOf('borrows');

    // authors must come before books (books FK → authors)
    expect(authorsIdx).toBeLessThan(booksIdx);
    // books must come before borrows (borrows FK → books)
    expect(booksIdx).toBeLessThan(borrowsIdx);
    // members must come before borrows (borrows FK → members)
    expect(membersIdx).toBeLessThan(borrowsIdx);
  });

  it('circular references use ALTER TABLE … ADD CONSTRAINT', () => {
    const sql = generateSql(circularRefs, 'postgresql');

    // Both CREATE TABLEs should exist
    expect(sql).toContain('CREATE TABLE "employees"');
    expect(sql).toContain('CREATE TABLE "departments"');

    // At least one ALTER TABLE should exist for the circular FK
    expect(sql).toContain('ALTER TABLE');
    expect(sql).toContain('ADD CONSTRAINT');
  });

  it('self-referencing table uses inline FOREIGN KEY', () => {
    const sql = generateSql(selfReference, 'postgresql');
    expect(sql).toContain('CREATE TABLE "categories"');
    expect(sql).toContain('FOREIGN KEY ("parent_id") REFERENCES "categories"("id") ON DELETE CASCADE');
    // Should NOT use ALTER TABLE for self-references
    expect(sql).not.toContain('ALTER TABLE');
  });

  it('string default values with single quotes are escaped', () => {
    const sql = generateSql(stringDefaults, 'postgresql');
    // "it's a test" should become 'it''s a test'
    expect(sql).toContain("DEFAULT 'it''s a test'");
  });

  it('boolean default value FALSE is emitted', () => {
    const sql = generateSql(stringDefaults, 'postgresql');
    expect(sql).toContain('DEFAULT FALSE');
  });

  it('null default value is emitted as NULL', () => {
    const sql = generateSql(stringDefaults, 'postgresql');
    expect(sql).toContain('DEFAULT NULL');
  });

  it('output ends with a newline', () => {
    const sql = generateSql(validMinimal, 'postgresql');
    expect(sql.endsWith('\n')).toBe(true);
  });

  it('deterministic: same schema produces same output', () => {
    const a = generateSql(validLibrary, 'postgresql');
    const b = generateSql(validLibrary, 'postgresql');
    expect(a).toBe(b);
  });

  it('MySQL uses backtick quoting', () => {
    const sql = generateSql(validMinimal, 'mysql');
    expect(sql).toContain('`users`');
    expect(sql).toContain('`id`');
  });

  it('PostgreSQL uses double-quote quoting', () => {
    const sql = generateSql(validMinimal, 'postgresql');
    expect(sql).toContain('"users"');
    expect(sql).toContain('"id"');
  });

  it('NOT NULL is emitted for non-nullable columns', () => {
    const sql = generateSql(validAllTypes, 'postgresql');
    expect(sql).toContain('"product_name" VARCHAR(200) NOT NULL');
  });

  it('nullable columns omit NOT NULL', () => {
    const sql = generateSql(validAllTypes, 'postgresql');
    // "description" TEXT is nullable — should not have NOT NULL
    const descLine = sql.split('\n').find((l) => l.includes('"description"'));
    expect(descLine).toBeDefined();
    expect(descLine).not.toContain('NOT NULL');
  });

  it('UNIQUE is emitted for unique non-PK columns', () => {
    const sql = generateSql(validLibrary, 'postgresql');
    expect(sql).toContain('"email" VARCHAR(254) NOT NULL UNIQUE');
  });

  it('ON DELETE action is correct', () => {
    const sql = generateSql(validLibrary, 'postgresql');
    expect(sql).toContain('ON DELETE CASCADE');
    expect(sql).toContain('ON DELETE RESTRICT');
  });
});
