/**
 * Golden-file tests for the SQL generator.
 * T2.6: schema fixture → expected .sql file.
 */

import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, it, expect } from 'vitest';
import { generateSql } from '../../src/sql/sql.generator.js';
import { sqlType, autoIncrementSyntax } from '../../src/sql/type-map.js';
import { validMinimal, validLibrary, validAllTypes } from '../fixtures/schemas.js';
import { circularRefs, stringDefaults, selfReference } from '../fixtures/sql-fixtures.js';
import type { Column } from '../../src/schema/schema.types.js';

const GOLDEN_DIR = resolve(import.meta.dirname, '../fixtures/golden');

function readGolden(name: string): string {
  return readFileSync(resolve(GOLDEN_DIR, name), 'utf-8');
}

// Normalize line endings for cross-platform comparison
function normalize(s: string): string {
  return s.replace(/\r\n/g, '\n');
}

// ── Type map tests ────────────────────────────────────────────────────

describe('type-map', () => {
  const baseCol: Column = {
    id: 'c_test',
    name: 'test',
    type: 'INTEGER',
    primaryKey: false,
    nullable: false,
    unique: false,
  };

  describe('sqlType — PostgreSQL', () => {
    it('maps INTEGER → INTEGER', () => {
      expect(sqlType({ ...baseCol, type: 'INTEGER' }, 'postgresql')).toBe('INTEGER');
    });

    it('maps BIGINT → BIGINT', () => {
      expect(sqlType({ ...baseCol, type: 'BIGINT' }, 'postgresql')).toBe('BIGINT');
    });

    it('maps VARCHAR with length', () => {
      expect(sqlType({ ...baseCol, type: 'VARCHAR', length: 255 }, 'postgresql')).toBe('VARCHAR(255)');
    });

    it('maps TEXT → TEXT', () => {
      expect(sqlType({ ...baseCol, type: 'TEXT' }, 'postgresql')).toBe('TEXT');
    });

    it('maps BOOLEAN → BOOLEAN', () => {
      expect(sqlType({ ...baseCol, type: 'BOOLEAN' }, 'postgresql')).toBe('BOOLEAN');
    });

    it('maps DATE → DATE', () => {
      expect(sqlType({ ...baseCol, type: 'DATE' }, 'postgresql')).toBe('DATE');
    });

    it('maps TIMESTAMP → TIMESTAMP', () => {
      expect(sqlType({ ...baseCol, type: 'TIMESTAMP' }, 'postgresql')).toBe('TIMESTAMP');
    });

    it('maps DECIMAL with precision and scale → NUMERIC(p,s)', () => {
      expect(sqlType({ ...baseCol, type: 'DECIMAL', precision: 10, scale: 2 }, 'postgresql')).toBe('NUMERIC(10,2)');
    });

    it('maps DECIMAL with precision only → NUMERIC(p)', () => {
      expect(sqlType({ ...baseCol, type: 'DECIMAL', precision: 10 }, 'postgresql')).toBe('NUMERIC(10)');
    });

    it('maps UUID → UUID', () => {
      expect(sqlType({ ...baseCol, type: 'UUID' }, 'postgresql')).toBe('UUID');
    });
  });

  describe('sqlType — MySQL', () => {
    it('maps INTEGER → INT', () => {
      expect(sqlType({ ...baseCol, type: 'INTEGER' }, 'mysql')).toBe('INT');
    });

    it('maps VARCHAR with length', () => {
      expect(sqlType({ ...baseCol, type: 'VARCHAR', length: 100 }, 'mysql')).toBe('VARCHAR(100)');
    });

    it('maps DECIMAL → DECIMAL(p,s)', () => {
      expect(sqlType({ ...baseCol, type: 'DECIMAL', precision: 8, scale: 4 }, 'mysql')).toBe('DECIMAL(8,4)');
    });

    it('maps UUID → CHAR(36)', () => {
      expect(sqlType({ ...baseCol, type: 'UUID' }, 'mysql')).toBe('CHAR(36)');
    });
  });

  describe('autoIncrementSyntax', () => {
    it('returns GENERATED BY DEFAULT AS IDENTITY for PostgreSQL', () => {
      expect(autoIncrementSyntax('postgresql')).toBe('GENERATED BY DEFAULT AS IDENTITY');
    });

    it('returns AUTO_INCREMENT for MySQL', () => {
      expect(autoIncrementSyntax('mysql')).toBe('AUTO_INCREMENT');
    });
  });
});

