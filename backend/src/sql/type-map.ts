/**
 * Logical column type → SQL dialect type mapping.
 * Per requirements.md §8.
 */

import type { ColumnType, Dialect, Column } from '../schema/schema.types.js';

// ── Type mapping tables ──────────────────────────────────────────────

const PG_TYPES: Record<ColumnType, string> = {
  INTEGER: 'INTEGER',
  BIGINT: 'BIGINT',
  VARCHAR: 'VARCHAR',
  TEXT: 'TEXT',
  BOOLEAN: 'BOOLEAN',
  DATE: 'DATE',
  TIMESTAMP: 'TIMESTAMP',
  DECIMAL: 'NUMERIC',
  UUID: 'UUID',
};

const MYSQL_TYPES: Record<ColumnType, string> = {
  INTEGER: 'INT',
  BIGINT: 'BIGINT',
  VARCHAR: 'VARCHAR',
  TEXT: 'TEXT',
  BOOLEAN: 'BOOLEAN',
  DATE: 'DATE',
  TIMESTAMP: 'TIMESTAMP',
  DECIMAL: 'DECIMAL',
  UUID: 'CHAR(36)',
};

const TYPE_MAPS: Record<Dialect, Record<ColumnType, string>> = {
  postgresql: PG_TYPES,
  mysql: MYSQL_TYPES,
};

/**
 * Returns the SQL type string for a column in the given dialect.
 * Appends length/precision/scale where applicable.
 */
export function sqlType(col: Column, dialect: Dialect): string {
  const base = TYPE_MAPS[dialect][col.type];

  if (col.type === 'VARCHAR' && col.length !== undefined) {
    return `${base}(${col.length})`;
  }

  if (col.type === 'DECIMAL') {
    if (col.precision !== undefined && col.scale !== undefined) {
      return `${base}(${col.precision},${col.scale})`;
    }
    if (col.precision !== undefined) {
      return `${base}(${col.precision})`;
    }
  }

  // UUID in MySQL is already CHAR(36) — don't append anything
  return base;
}

/**
 * Returns the auto-increment syntax for the given dialect.
 */
export function autoIncrementSyntax(dialect: Dialect): string {
  return dialect === 'postgresql'
    ? 'GENERATED BY DEFAULT AS IDENTITY'
    : 'AUTO_INCREMENT';
}
